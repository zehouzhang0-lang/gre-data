const words=(await repo.getState()).vocabulary.filter(w=>!w.deleted&&w.meaning).slice(0,37).map(w=>w.word);
await repo.rate([words[0]],'partial');
await repo.saveEvent('vocab_upsert',{word:words[1],pos:'adj.',meaning:'手机个人释义测试',note:'隔离测试'});
await repo.saveEvent('vocab_session',{session_id:crypto.randomUUID(),words,meaning_passes:2});
await repo.saveEvent('vocab_card_reading',{items:[{word:words[0],count:3,viewed_at:'2026-10-17T16:55:00Z',impression:'partial'}]});
await repo.setSettings({catalogUpdate:{revision:CATALOG_REVISION},wallPage:2,display:{columns:3,height:60,font:16}});
